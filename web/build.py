#!/usr/bin/env python3
"""Bundle the TWANG web UI into one self-contained page.

Outputs:
  build/web/index.html             the page (works standalone as the simulator)
  build/web/index.html.gz          what the firmware serves
  TWANG32/src/app/web_ui.h         gzipped page as a C array, compiled into the firmware
  TWANG32/src/app/default_campaign.h  the stock campaign (minified), used on first boot / factory reset

Requires build/twang.wasm (run wasm/build.sh first) and the two fonts in web/fonts/.
"""
import base64
import gzip
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
OUT = ROOT / "build" / "web"
APP = ROOT / "TWANG32" / "src" / "app"


def read(p):
    return (WEB / p).read_text(encoding="utf-8")


def font_face(family, path, weight, style="normal"):
    data = base64.b64encode(path.read_bytes()).decode()
    return (f"@font-face{{font-family:'{family}';font-style:{style};font-display:swap;font-weight:{weight};"
            f"src:url(data:font/woff2;base64,{data}) format('woff2');}}")


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    return f"const uint8_t {name}[] PROGMEM = {{\n" + "\n".join(lines) + f"\n}};\nconst size_t {name}_LEN = {len(data)};\n"


def main():
    wasm = ROOT / "build" / "twang.wasm"
    if not wasm.exists():
        sys.exit("build/twang.wasm is missing: run wasm/build.sh first")
    fonts_dir = WEB / "fonts"
    fonts = font_face("Grenze Gotisch", fonts_dir / "grenze-gotisch-latin-700-normal.woff2", 700)
    fonts += font_face("Archivo Variable", fonts_dir / "archivo-latin-wght-normal.woff2", "100 900")

    camp_next = json.loads((ROOT / "campaign" / "next.json").read_text())
    camp_classic = json.loads((ROOT / "campaign" / "classic.json").read_text())
    data = {
        "wasm": base64.b64encode(wasm.read_bytes()).decode(),
        "campaigns": {"next": camp_next, "classic": camp_classic},
    }
    page = read("index.html")
    page = page.replace("/*@@FONTS@@*/", fonts)
    page = page.replace("/*@@CSS@@*/", read("style.css"))
    page = page.replace("/*@@DATA@@*/", "window.TWANG_DATA=" + json.dumps(data, separators=(",", ":")) + ";")
    page = page.replace("/*@@APP@@*/", read("app.js"))
    page = page.replace("/*@@EDITOR@@*/", read("editor.js"))

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "index.html").write_text(page, encoding="utf-8")
    gz = gzip.compress(page.encode("utf-8"), compresslevel=9, mtime=0)
    (OUT / "index.html.gz").write_bytes(gz)

    # artifact flavour: the host supplies the document wrapper, so drop ours
    art = page.replace("<!doctype html>\n", "").replace('<html lang="en">\n', "").replace("</html>\n", "")
    art = art.replace("<head>\n", "").replace("</head>\n", "").replace("<body>\n", "").replace("</body>\n", "")
    art = art.replace('<meta charset="utf-8">\n', "").replace('<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n', "")
    (OUT / "artifact.html").write_text(art, encoding="utf-8")

    APP.mkdir(parents=True, exist_ok=True)
    header = ("// Generated by web/build.py - do not edit. The whole web UI, gzipped.\n"
              "#pragma once\n#include <Arduino.h>\n\n" + c_array("WEB_UI_GZ", gz))
    (APP / "web_ui.h").write_text(header)

    # stock campaign, minified, as a plain string (small enough that compression isn't worth the code)
    stock = json.dumps(camp_next, separators=(",", ":")).encode()
    header = ("// Generated by web/build.py - do not edit. campaign/next.json, minified.\n"
              "#pragma once\n#include <Arduino.h>\n\n" + c_array("DEFAULT_CAMPAIGN", stock + b"\0"))
    (APP / "default_campaign.h").write_text(header)

    print(f"page {len(page)/1024:.0f} KB, gzipped {len(gz)/1024:.0f} KB; default campaign {len(stock)/1024:.1f} KB")


if __name__ == "__main__":
    main()
